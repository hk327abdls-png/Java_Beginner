/* 以下の予約語（キーワード）を使用して、Javaのコードを作成してください。

intという予約語を使用して、整数型の変数を宣言し、値を代入します。
ifという予約語を使用して、条件式を作成し、条件が真の場合に特定の処理を実行します。
forという予約語を使用して、ループ処理を行います。 */

public class Main {
    public static void main(String[] args) {
        int number = 5;

        if (number > 0) {
            System.out.println("数値は正です。");
        }
        for (int i = 1; i <=     5; i++) {
            System.out.println("ループの繰り返し回数: " + i);
        }
    }
}