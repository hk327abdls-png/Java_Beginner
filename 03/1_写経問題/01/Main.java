// 【このファイルで確認すること】
// if-else 文の基本的な書き方を体験する。
// 条件式（比較演算子 >= ）を使って処理を分岐させる流れを確認する。
//
// 【写経のポイント】
// ・if 文の書き方: 「if (条件式) { 真の処理 } else { 偽の処理 }」
// ・比較演算子 >= は「以上」を表す（例: age >= 18 は「age が 18 以上」）
// ・age にさまざまな値を入れて動作が変わることを確認してみること

public class Main {
    public static void main(String[] args) {
        // int型変数 age を宣言して適切な年齢を代入する（例: 20 や 15 など）
        // ヒント: int age = 20;
        int age = 31;

        // age が 18 以上なら "成年です"、それ以外なら "未成年です" と出力する
        // ヒント: if (age >= 18) { ... } else { ... } の形で書く
        // 期待出力（age=20 の場合）: 成年です
        // 期待出力（age=15 の場合）: 未成年です
        if (age >= 18) {
            System.out.println("成年です");
        } else {
            System.out.println("未成年です");
        }
    }
}
